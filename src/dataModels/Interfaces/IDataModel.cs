using System.Text.Json.Nodes;

namespace GYI.src.dataModels.interfaces
{
    public interface IDataModel
    {
        /// <summary>
        /// Returns a JsonObject representation of the data model according compatible with the expected DB schema.
        ///     The generated JSON may omit certain fields that are not required for the DB;
        ///         such omissions are supposed to be notified in the documentation of the implementing class.
        /// </summary>
        /// <returns></returns>
        public JsonObject GetJSONData();

        /// <summary>
        /// Returns a string representation of the JSON data that would have been generated by GetJSONData().
        /// </summary>
        /// <returns></returns>
        public string GetJSONDataString()
        {
            return GetJSONData().ToJsonString();
        }
    }
}